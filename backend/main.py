@app.get("/recetas")
def obtener_recetas():
    conn = get_connection()
    cursor = conn.cursor()
    cursor.execute("""
        SELECT r.id_receta, r.id_expediente, m.nombre_completo, 
               TO_CHAR(r.fecha_emision, 'YYYY-MM-DD'), TO_CHAR(r.fecha_vencimiento, 'YYYY-MM-DD'), r.estado
        FROM receta_medica r
        JOIN medico m ON r.id_medico = m.id_medico
    """)
    filas = cursor.fetchall()
    conn.close()
    return [{"id_receta": f[0], "id_expediente": f[1], "medico": f[2], "fecha_emision": f[3], "fecha_vencimiento": f[4], "estado": f[5]} for f in filas]

@app.post("/recetas")
def crear_receta(receta: RecetaSchema):
    conn = get_connection()
    cursor = conn.cursor()
    
    # 1. Crear Receta
    out_id = cursor.var(oracledb.NUMBER)
    cursor.execute("""
        INSERT INTO receta_medica (id_expediente, id_medico, fecha_emision, fecha_vencimiento, estado)
        VALUES (:1, :2, SYSDATE, TO_DATE(:3, 'YYYY-MM-DD'), :4)
        RETURNING id_receta INTO :5
    """, [receta.id_expediente, receta.id_medico, receta.fecha_vencimiento, receta.estado, out_id])
    
    id_receta_creada = out_id.getvalue()[0]
    
    # 2. Registrar en Detalle Receta
    cursor.execute("""
        INSERT INTO detalle_receta (id_receta, id_medicamento)
        VALUES (:1, :2)
    """, [id_receta_creada, receta.id_medicamento])
    
    # 3. Descontar Stock de Medicamento
    cursor.execute("""
        UPDATE medicamento 
        SET stock_disponible = stock_disponible - 1 
        WHERE id_medicamento = :1 AND stock_disponible > 0
    """, [receta.id_medicamento])

    registrar_auditoria(cursor, "MÉDICO", "EMITIR_RECETA", "receta_medica", f"Receta #{id_receta_creada} emitida con firma digital hash")
    conn.commit()
    conn.close()
    return {"status": "ok", "mensaje": f"Receta #{id_receta_creada} emitida y firmada digitalmente"}


