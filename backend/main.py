@app.get("/reportes/kpis")
def obtener_kpis():
    """Consolida las métricas e indicadores de rendimiento hospitalario"""
    conn = get_connection()
    cursor = conn.cursor()
    
    cursor.execute("SELECT NVL(SUM(monto_total), 0) FROM factura WHERE estado = 'Pagada' OR estado = 'Pendiente'")
    total_ingresos = cursor.fetchone()[0]
    
    cursor.execute("SELECT COUNT(*) FROM cita")
    total_citas = cursor.fetchone()[0]
    
    cursor.execute("SELECT COUNT(*) FROM receta_medica WHERE estado = 'Vigente'")
    recetas_vigentes = cursor.fetchone()[0]
    
    cursor.execute("SELECT COUNT(*) FROM resultado_laboratorio WHERE es_critico = 1")
    examenes_criticos = cursor.fetchone()[0]
    
    conn.close()
    
    return {
        "ingresos_totales": total_ingresos,
        "total_citas": total_citas,
        "recetas_vigentes": recetas_vigentes,
        "examenes_criticos": examenes_criticos
    }

