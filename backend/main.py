    tablas_creadas = 0

    for sql in tablas_sql:
        try:
            cursor.execute(sql)
            tablas_creadas += 1
        except oracledb.DatabaseError as e:
            error_obj, = e.args
            if error_obj.code != 955: # Tabla ya existente
                errores.append(str(error_obj.message))

    conn.commit()
    conn.close()

    if errores:
        return {"status": "advertencia", "errores": errores, "tablas_creadas": tablas_creadas}
    
    return {"status": "ok", "mensaje": "Estructura completa de tablas e indicadores inicializada en Oracle DB"}


