@app.get("/citas")
def obtener_citas():
    conn = get_connection()
    cursor = conn.cursor()
    cursor.execute("""
        SELECT c.id_cita, TO_CHAR(c.fecha_hora, 'YYYY-MM-DD HH24:MI'), 
               p.nombre_completo, m.nombre_completo, c.estado
        FROM cita c
        JOIN paciente p ON c.id_paciente = p.id_paciente
        JOIN medico m ON c.id_medico = m.id_medico
        ORDER BY c.fecha_hora DESC
    """)
    filas = cursor.fetchall()
    conn.close()
    return [{"id_cita": f[0], "fecha_hora": f[1], "paciente": f[2], "medico": f[3], "estado": f[4]} for f in filas]

@app.post("/citas")
def crear_cita(cita: CitaSchema):
    conn = get_connection()
    cursor = conn.cursor()
    
    # 1. Validar RN-02: Conflicto de horario con el médico
    cursor.execute("""
        SELECT COUNT(*) FROM cita 
        WHERE id_medico = :1 
        AND fecha_hora = TO_TIMESTAMP(:2, 'YYYY-MM-DD"T"HH24:MI')
        AND estado != 'Cancelada'
    """, [cita.id_medico, cita.fecha_hora])
    
    if cursor.fetchone()[0] > 0:
        conn.close()
        raise HTTPException(status_code=400, detail="RN-02: El especialista ya posee una cita agendada en este horario exacto.")

    # 2. Validación de Jornada Laboral (Si el médico tiene jornadas definidas)
    cursor.execute("SELECT COUNT(*) FROM jornada_medico WHERE id_medico = :1", [cita.id_medico])
    tiene_jornadas = cursor.fetchone()[0]
    
    if tiene_jornadas > 0:
        cursor.execute("""
            SELECT COUNT(*) FROM jornada_medico
            WHERE id_medico = :1
            AND dia_semana = TRIM(TO_CHAR(TO_TIMESTAMP(:2, 'YYYY-MM-DD"T"HH24:MI'), 'DAY', 'NLS_DATE_LANGUAGE=SPANISH'))
            AND TO_CHAR(TO_TIMESTAMP(:2, 'YYYY-MM-DD"T"HH24:MI'), 'HH24:MI') BETWEEN hora_inicio AND hora_fin
        """, [cita.id_medico, cita.fecha_hora])
        
        if cursor.fetchone()[0] == 0:
            conn.close()
            raise HTTPException(status_code=400, detail="El horario seleccionado está fuera de la jornada médica configurada para este especialista.")

    cursor.execute("""
        INSERT INTO cita (fecha_hora, id_paciente, id_medico, estado)
        VALUES (TO_TIMESTAMP(:1, 'YYYY-MM-DD"T"HH24:MI'), :2, :3, :4)
    """, [cita.fecha_hora, cita.id_paciente, cita.id_medico, cita.estado])
    
    registrar_auditoria(cursor, "SISTEMA", "CREAR_CITA", "cita", f"Cita programada para Paciente #{cita.id_paciente} con Médico #{cita.id_medico}")
    conn.commit()
    conn.close()
    return {"status": "ok", "mensaje": "Cita agendada exitosamente"}


