@app.post("/resultados-laboratorio")
def registrar_resultado_lab(res: ResultadoLabSchema):
    conn = get_connection()
    cursor = conn.cursor()
    
    try:
        cursor.execute("SELECT COUNT(*) FROM laboratorio_externo WHERE id_laboratorio = :1", [res.id_laboratorio])
        existe_lab = cursor.fetchone()[0]
        
        if existe_lab == 0:
            cursor.execute("""
                INSERT INTO laboratorio_externo (id_laboratorio, nombre_laboratorio) 
                VALUES (:1, 'Laboratorio Central Hospitalario')
            """, [res.id_laboratorio])

        es_critico_val = int(res.es_critico)

        cursor.execute("""
            INSERT INTO resultado_laboratorio (id_expediente, id_laboratorio, tipo_examen, pdf_url, es_critico, fecha_recepcion)
            VALUES (:1, :2, :3, :4, :5, SYSTIMESTAMP)
        """, [res.id_expediente, res.id_laboratorio, res.tipo_examen, res.pdf_url, es_critico_val])
        
        registrar_auditoria(cursor, "LABORATORIO", "REGISTRAR_RESULTADO", "resultado_laboratorio", f"Examen {res.tipo_examen} registrado. Crítico: {es_critico_val}")
        
        conn.commit()
        conn.close()

        alerta = "⚠️ ALERTA CRÍTICA (RF-19): Se ha notificado al médico tratante sobre este examen." if es_critico_val == 1 else "Resultado de laboratorio registrado con éxito."
        return {"status": "ok", "mensaje": alerta}

    except Exception as e:
        conn.close()
        print(f"Error en Laboratorio: {str(e)}")
        raise HTTPException(status_code=400, detail=f"Error en BD: {str(e)}")


